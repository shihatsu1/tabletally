const dictionaries: Record<Lang, Record<string, string>> = { en, tl };

function initialLang(): Lang {
  const saved = getItem('tt.lang');
  if (saved === 'en' || saved === 'tl') return saved;
  return typeof navigator !== 'undefined' && navigator.language?.toLowerCase().startsWith('fil') ? 'tl' : 'en';
}

export const ui = $state<{ lang: Lang }>({ lang: initialLang() });

export function setLang(lang: Lang): void {
  ui.lang = lang;
  setItem('tt.lang', lang);
  if (typeof document !== 'undefined') document.documentElement.lang = lang === 'tl' ? 'fil' : 'en';
}

/** Translate a key. Missing Tagalog strings fall back to English, then to the key itself. */
/**
 * Look up a string and fill in its {placeholders}. When `vars.n` is 1 and a `<key>.one` string exists, that one is
 * used, so English can say "1 chip" and "2 chips" (Filipino nouns do not change, so it needs no `.one` strings).
 */
export function t(key: string, vars: Record<string, string | number> = {}): string {
  const dict = dictionaries[ui.lang];
  const one = vars.n === 1 ? dict[`${key}.one`] : undefined;
  const text = one ?? dict[key] ?? en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`));
}
